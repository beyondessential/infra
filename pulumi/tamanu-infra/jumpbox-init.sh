#!/bin/sh

### Script run at first boot only of the jumpbox instance
# https://gitlab.alpinelinux.org/alpine/cloud/tiny-cloud

set -eux
apk update

## Basic tooling to make a human operator's life easier
apk add \
  bash \
  curl \
  fish \
  git \
  jq \
  neovim \
  ripgrep

# Set fish as the default shell for the default user (alpine)
chsh -s /usr/bin/fish alpine

## PostgreSQL client so one can access the database from the jumpbox if wanted
apk add postgresql-client

## HAProxy configured to forward Postgres to the database
#
# This is safe to expose because this jumpbox is configured to not allow any
# ingress! So the only way to get to it is via Tailscale.
apk add haproxy

# The %DB_ENDPOINT% string below is replaced by Pulumi with the actual
# database endpoint. For HAProxy, it needs to have the port number.
cat <<EOF > /etc/haproxy/haproxy.cfg
global
    daemon
    chroot      /var/lib/haproxy
    pidfile     /var/run/haproxy.pid
    maxconn     4000
    user        haproxy
    group       haproxy
    stats socket /var/lib/haproxy/stats

defaults
    mode                    tcp
    log                     global
    option                  dontlognull
    retries                 3
    timeout queue           1m
    timeout connect         10s
    timeout client          1m
    timeout server          1m
    timeout check           10s
    maxconn                 3000

frontend psql
    bind *:5432
    default_backend             database

backend database
    server  db1  %DB_ENDPOINT%  check
EOF

service haproxy start
rc-update add haproxy

## Tailscale

# Enable IP forwarding, required for Tailscale
cat <<EOF > /etc/sysctl.d/99-tailscale.conf
net.ipv4.ip_forward = 1
net.ipv6.conf.all.forwarding = 1
EOF

apk add tailscale
service tailscale start
rc-update add tailscale

# Connect to the Tailscale network
# The %TAILSCALE_*% strings below are replaced by Pulumi with the actual values.
# --hostname = use a custom string for the name in the Tailscale UI/API
# --ssh = allow SSH access to the instance via Tailscale (the entire point!)
# --auth-key = a single-use authkey generated by Pulumi just in time for this
tailscale up --hostname %TAILSCALE_NAME% --ssh --auth-key %TAILSCALE_AUTH_KEY%
